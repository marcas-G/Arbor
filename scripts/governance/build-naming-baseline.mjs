// One-shot generator for scripts/governance/naming-baseline.json.
// Usage: node scripts/governance/build-naming-baseline.mjs > naming-baseline.json
// Run at the adoption commit; the result is frozen inventory.
import { execFileSync } from "node:child_process";
import {
  isOutOfScope,
  isSourcePath,
  PATH_PATTERN,
  SYMBOL_PATTERN,
  TEST_NAME_PATTERN,
} from "./semantic-naming-lib.mjs";

const git = (args) =>
  execFileSync("git", args, {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }).trim();

const paths = git(["ls-files", "-z"]).split("\0").filter(Boolean);
const pathEntries = [];
const symbolEntries = [];
const testEntries = [];
for (const path of paths) {
  if (isOutOfScope(path)) continue;
  if (isSourcePath(path) && PATH_PATTERN.test(path)) {
    pathEntries.push({ path, evidence: path });
  }
  if (!isSourcePath(path)) continue;
  const lines = git(["show", `HEAD:${path}`]).split(/\r\n|\n|\r/u);
  const seenSymbols = new Set();
  const seenNames = new Set();
  lines.forEach((line, index) => {
    const symbolMatch = SYMBOL_PATTERN.exec(line);
    if (symbolMatch) {
      const symbol = symbolMatch[0].trim().split(/\s+/u).pop();
      if (!seenSymbols.has(symbol)) {
        seenSymbols.add(symbol);
        symbolEntries.push({
          path,
          line: index + 1,
          evidence: line.trim(),
          symbol,
        });
      }
    }
    const nameMatch = TEST_NAME_PATTERN.exec(line);
    if (nameMatch && !seenNames.has(nameMatch[1])) {
      seenNames.add(nameMatch[1]);
      testEntries.push({ path, line: index + 1, evidence: line.trim() });
    }
  });
}
const baseline = {
  schema: "arbor/semantic-naming-baseline/v1",
  comment:
    "Legacy semantic-naming inventory frozen at the adoption commit " +
    "(architecture object 11, first ratchet slice). Generated by scanning the " +
    "tracked tree; entries are grandfathered and shrink monotonically. A path " +
    "here is exempt from the path category only; the symbol and test-name " +
    "categories still apply to lines added after the baseline commit.",
  inventoryBase: git(["rev-parse", "HEAD"]),
  categories: {
    path: pathEntries,
    symbol: symbolEntries,
    "test-name": testEntries,
  },
  exemptions: { paths: pathEntries },
};
console.log(JSON.stringify(baseline, null, 2));
