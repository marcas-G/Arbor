#!/usr/bin/env python3
"""Generate the bundled command filters with the system libseccomp.

Build/development tool only; installed Arbor needs neither Python nor the
libseccomp development headers. setpriv loads the generated BPF in the sandbox.
The relay starts before this filter, so it can open its one private Unix channel.
"""

import base64
import ctypes
import ctypes.util
import errno
import pathlib
import tempfile


class Comparison(ctypes.Structure):
    _fields_ = [
        ("arg", ctypes.c_uint),
        ("op", ctypes.c_int),
        ("datum_a", ctypes.c_uint64),
        ("datum_b", ctypes.c_uint64),
    ]


library = ctypes.util.find_library("seccomp")
if library is None:
    raise RuntimeError("Install libseccomp to regenerate the command filters")
lib = ctypes.CDLL(library, use_errno=True)
lib.seccomp_init.argtypes = [ctypes.c_uint32]
lib.seccomp_init.restype = ctypes.c_void_p
lib.seccomp_arch_native.restype = ctypes.c_uint32
lib.seccomp_arch_resolve_name.argtypes = [ctypes.c_char_p]
lib.seccomp_arch_resolve_name.restype = ctypes.c_uint32
lib.seccomp_arch_add.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
lib.seccomp_arch_remove.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
lib.seccomp_syscall_resolve_name.argtypes = [ctypes.c_char_p]
lib.seccomp_syscall_resolve_name.restype = ctypes.c_int
lib.seccomp_rule_add_array.argtypes = [
    ctypes.c_void_p, ctypes.c_uint32, ctypes.c_int, ctypes.c_uint,
    ctypes.POINTER(Comparison),
]
lib.seccomp_export_bpf.argtypes = [ctypes.c_void_p, ctypes.c_int]
lib.seccomp_release.argtypes = [ctypes.c_void_p]


def check(result):
    if result != 0:
        raise RuntimeError(f"libseccomp: {result}")


def generate(architecture):
    # SCMP_ACT_ALLOW; libseccomp's default bad-architecture action rejects
    # compatibility ABIs as well. Do not leave socketcall as an escape route.
    context = lib.seccomp_init(0x7FFF0000)
    if not context:
        raise RuntimeError("seccomp_init failed")
    try:
        target = lib.seccomp_arch_resolve_name(architecture.encode())
        if not target:
            raise RuntimeError(f"Unknown architecture: {architecture}")
        if target != lib.seccomp_arch_native():
            check(lib.seccomp_arch_add(context, target))
            check(lib.seccomp_arch_remove(context, lib.seccomp_arch_native()))

        def deny(name, action=0x50000 | errno.EPERM, comparisons=()):
            syscall = lib.seccomp_syscall_resolve_name(name.encode())
            # Negative pseudo-syscall values are valid for cross-architecture
            # translation; -1 alone means an unknown syscall name.
            if syscall == -1:
                raise RuntimeError(f"Unknown syscall: {name}")
            rules = (Comparison * len(comparisons))(*comparisons)
            check(lib.seccomp_rule_add_array(
                context, action, syscall, len(rules), rules,
            ))

        # SCMP_CMP_EQ. AF_UNIX socketpair remains usable for child-process IPC;
        # a new pair cannot connect to a pathname socket outside this command.
        deny("socket", comparisons=[Comparison(0, 4, 1, 0)])
        for name in [
            "unshare", "setns", "mount", "umount2", "pivot_root",
            "move_mount", "open_tree", "fsopen", "fsconfig", "fsmount",
            "mount_setattr", "ptrace", "process_vm_readv", "process_vm_writev",
            "pidfd_getfd", "io_uring_setup", "io_uring_enter", "io_uring_register",
            "open_by_handle_at", "bpf", "perf_event_open",
        ]:
            deny(name)
        # clone3's flags live behind a pointer. ENOSYS lets libc use ordinary
        # clone for threads and subprocesses; namespace-bearing clone is denied.
        deny("clone3", 0x50000 | errno.ENOSYS)
        for flag in [
            0x00020000, 0x02000000, 0x04000000, 0x08000000,
            0x10000000, 0x20000000, 0x40000000, 0x80,
        ]:
            deny("clone", comparisons=[Comparison(0, 7, flag, flag)])
        with tempfile.TemporaryFile() as output:
            check(lib.seccomp_export_bpf(context, output.fileno()))
            output.seek(0)
            return base64.b64encode(output.read()).decode("ascii")
    finally:
        lib.seccomp_release(context)


filters = {"x64": generate("x86_64"), "arm64": generate("aarch64")}
target = pathlib.Path(__file__).parent / "src" / "index.ts"
start_marker = "// BEGIN GENERATED COMMAND FILTERS\n"
end_marker = "// END GENERATED COMMAND FILTERS\n"
source = target.read_text()
start = source.index(start_marker)
end = source.index(end_marker, start) + len(end_marker)
generated = (
    start_marker
    + "// Generated by generate-command-filter.py using libseccomp.\n"
    + "// Native architecture only; compatibility ABIs fail closed.\n"
    + "const commandFilters: Readonly<Record<string, string>> = {\n"
    + "".join(f'  {arch}: "{value}",\n' for arch, value in filters.items())
    + "};\n\n"
    + "const linuxCommandFilter = (architecture: string): string | undefined =>\n"
    + "  commandFilters[architecture];\n"
    + end_marker
)
target.write_text(source[:start] + generated + source[end:])
