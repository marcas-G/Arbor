/** Verifies complete file bytes without asserting any Supported capability.
 * The independent installer can exercise artifact drift before issuing a
 * manifest, without inventing an authority row or self-referential evidence. */
export const verifyLinuxQualificationArtifacts = async (
  artifacts: ReadonlyArray<SandboxLinuxQualificationArtifactHashV2>,
  readArtifact: NonNullable<LinuxProbeInput["readQualificationArtifact"]>,
): Promise<boolean> => {
  try {
    return (
      await Promise.all(
        artifacts.map(async (artifact) => {
          const bytes = await readArtifact(artifact.role);
          return (
            bytes !== undefined &&
            createHash("sha256").update(bytes).digest("hex") === artifact.sha256
          );
        }),
      )
    ).every(Boolean);
  } catch {
    return false;
  }
};

/** Detect Linux prerequisites without creating cgroups or installing packages. */
export const probeLinuxBwrap = async (
  input: LinuxProbeInput,
): Promise<NativePosixCapability> => {
  let probe = input.probe;
  if (
    probe === undefined &&
    input.platform === "linux" &&
    input.run !== undefined
  ) {
    const probeCommand = input.run;
    const readFile = input.readFile ?? hostReadFile;
    const version = await probeCommand(LINUX_SANDBOX_EXECUTABLES.bwrap, [
      "--version",
    ]);
    const help = await probeCommand(LINUX_SANDBOX_EXECUTABLES.bwrap, [
      "--help",
    ]);
    const setprivHelp = await probeCommand(LINUX_SANDBOX_EXECUTABLES.setpriv, [
      "--help",
    ]);
    const controllers = await readFile("/sys/fs/cgroup/cgroup.controllers");
    const seccomp = await readFile("/proc/sys/kernel/seccomp/actions_avail");
    const namespace = async (flags: ReadonlyArray<string>) =>
      (await probeCommand(LINUX_SANDBOX_EXECUTABLES.bwrap, [
        "--die-with-parent",
        ...flags,
        "--ro-bind",
        "/",
        "/",
        "--proc",
        "/proc",
        "--",
        "/bin/true",
      ])) !== undefined;
    probe = {
      platform: input.platform,
      bwrapExecutable: prerequisiteStatus(
        version !== undefined && help !== undefined,
      ),
      userNamespaceProbe: prerequisiteStatus(
        await namespace(["--unshare-user"]),
      ),
      mountNamespaceProbe: prerequisiteStatus(
        await namespace(["--unshare-user"]),
      ),
      pidNamespaceProbe: prerequisiteStatus(
        await namespace(["--unshare-user", "--unshare-pid"]),
      ),
      networkNamespaceProbe: prerequisiteStatus(
        await namespace(["--unshare-user", "--unshare-net"]),
      ),
      cgroupV2Hierarchy: prerequisiteStatus(controllers !== undefined),
      cgroupPidsController: prerequisiteStatus(
        controllers?.split(/\s+/u).includes("pids") ?? false,
      ),
      cgroupMemoryController: prerequisiteStatus(
        controllers?.split(/\s+/u).includes("memory") ?? false,
      ),
      cgroupCpuController: prerequisiteStatus(
        controllers?.split(/\s+/u).includes("cpu") ?? false,
      ),
      seccompInterface: prerequisiteStatus(
        seccomp !== undefined &&
          help?.includes("--seccomp") === true &&
          help.includes("--disable-userns") &&
          help.includes("--assert-userns-disabled") &&
          setprivHelp?.includes("--seccomp-filter") === true &&
          linuxCommandFilter(process.arch) !== undefined,
      ),
      networkBrokerChannel: input.networkBrokerChannel ?? "Unavailable",
      processKillApi: prerequisiteStatus(
        process.platform === "linux" && typeof process.kill === "function",
      ),
    };
  }
  probe ??= unavailableLinuxProbe(input.platform);
  const allDetected = Object.values(linuxPrerequisiteStatuses(probe)).every(
    (status) => status === "PrerequisiteDetected",
  );
  const ruleSetVersion = input.enforcementRuleSetVersion ?? 1;
  const ruleSetBytes =
    ruleSetVersion === 2
      ? (() => {
          const ruleSet = sandboxEnforcementRuleSetV2ForProvider(
            LINUX_BWRAP_PROVIDER_ID,
          );
          return ruleSet === undefined
            ? undefined
            : encodeSandboxEnforcementRuleSetV2(ruleSet);
        })()
      : (() => {
          const ruleSet = sandboxEnforcementRuleSetV1ForProvider(
            LINUX_BWRAP_PROVIDER_ID,
          );
          return ruleSet === undefined
            ? undefined
            : encodeSandboxEnforcementRuleSetV1(ruleSet);
        })();
  const expectedRuleSetDigest =
    ruleSetBytes === undefined
      ? undefined
      : createHash("sha256").update(ruleSetBytes, "utf8").digest("hex");
  const candidateRows = input.qualificationRows ?? [];
  const rows = candidateRows.filter(
    (row) =>
      row.osBuild === (process.platform === "linux" ? release() : "") &&
      row.providerVersion.length > 0 &&
      row.capabilityRevision.length > 0 &&
      expectedRuleSetDigest !== undefined &&
      row.enforcementRuleSetDigest === expectedRuleSetDigest,
  );
  const tupleProofs = new Map<
    string,
    NonNullable<NativePosixCapability["qualificationTuples"]>[number]
  >();
  const qualifiedRows =
    ruleSetVersion === 2 && input.readQualificationEvidence !== undefined
      ? (
          await Promise.all(
            rows.map(async (row) => {
              const json = await input.readQualificationEvidence?.(
                row.qualificationEvidenceRef,
              );
              if (json === undefined) return undefined;
              const evidenceDigest = createHash("sha256")
                .update(json, "utf8")
                .digest("hex");
              const manifest =
                decodeCanonicalSandboxLinuxQualificationManifestV2(json);
              const artifactsMatch =
                manifest !== undefined &&
                input.readQualificationArtifact !== undefined &&
                (await verifyLinuxQualificationArtifacts(
                  manifest.artifactHashes,
                  input.readQualificationArtifact,
                ));
              const matches =
                manifest !== undefined &&
                artifactsMatch &&
                encodeSandboxLinuxQualificationManifestV2(manifest) === json &&
                `blob:sha256:${evidenceDigest}` ===
                  row.qualificationEvidenceRef &&
                manifest.providerVersion === row.providerVersion &&
                String(manifest.capabilityRevision) ===
                  row.capabilityRevision &&
                manifest.osBuild === row.osBuild &&
                manifest.profile === row.profile &&
                manifest.networkMode === row.networkMode &&
                manifest.enforcementRuleSetDigest ===
                  row.enforcementRuleSetDigest;
              if (!matches || manifest === undefined) return undefined;
              tupleProofs.set(row.qualificationEvidenceRef, {
                profile: row.profile,
                networkMode: row.networkMode,
                qualificationEvidenceRef: row.qualificationEvidenceRef,
                validatedLimits: manifest.validatedLimits,
              });
              return row;
            }),
          )
        ).filter((row): row is (typeof rows)[number] => row !== undefined)
      : ruleSetVersion === 2
        ? []
        : rows;
  const firstRow = qualifiedRows[0];
  const rowIdentityMatches =
    firstRow !== undefined &&
    qualifiedRows.every(
      (row) =>
        row.providerVersion === firstRow.providerVersion &&
        row.capabilityRevision === firstRow.capabilityRevision &&
        row.enforcementRuleSetDigest === firstRow.enforcementRuleSetDigest,
    );
  const qualified =
    allDetected && rowIdentityMatches && qualifiedRows.length > 0;
  const failureCode =
    input.platform !== "linux"
      ? "UnsupportedPlatform"
      : !allDetected
        ? "RequiredPrerequisiteUnavailable"
        : qualifiedRows.length === 0
          ? candidateRows.length === 0
            ? "QualificationEvidenceUnavailable"
            : expectedRuleSetDigest === undefined
              ? "ProviderRuleSetUnavailable"
              : "QualificationMaterialMismatch"
          : !rowIdentityMatches
            ? "QualificationMaterialMismatch"
            : null;
  return {
    providerId: LINUX_BWRAP_PROVIDER_ID,
    providerVersion: firstRow?.providerVersion ?? EXPERIMENTAL_VERSION,
    capabilityRevision: firstRow?.capabilityRevision ?? "linux-bwrap-probe-v1",
    probeEvidenceRef: prerequisiteDetectionRef(probe),
    enforcementRuleSetDigest: firstRow?.enforcementRuleSetDigest ?? null,
    qualificationEvidenceRef: firstRow?.qualificationEvidenceRef ?? null,
    ...(qualifiedRows.length > 0
      ? {
          qualificationEvidenceRefs: qualifiedRows.map(
            (row) => row.qualificationEvidenceRef,
          ),
          ...(ruleSetVersion === 2
            ? {
                qualificationTuples: qualifiedRows.flatMap((row) => {
                  const proof = tupleProofs.get(row.qualificationEvidenceRef);
                  return proof === undefined ? [] : [proof];
                }),
              }
            : {}),
        }
      : {}),
    status: qualified ? "Supported" : "Experimental",
    boundary: "OsEnforced",
    profiles: [...new Set(qualifiedRows.map((row) => row.profile))],
    networkModes: [...new Set(qualifiedRows.map((row) => row.networkMode))],
    failureCode,
    prerequisites: linuxPrerequisiteStatuses(probe),
  };
};

