const safeRef = /^[a-z][a-z0-9_-]{0,63}$/u;
const safeEnvName = /^[A-Za-z_][A-Za-z0-9_]*$/u;

const hostToolchainRoots = [
  "/usr",
  "/bin",
  "/sbin",
  "/lib",
  "/lib64",
  "/usr/local",
  // Debian-family tool selectors (cc, c++, java, ...) point through here.
  // The fixed symlink catalog is read-only; their targets must still exist
  // within the mounted toolchain. No other /etc content is admitted.
  "/etc/alternatives",
  // V2 keeps TLS end-to-end and deliberately does not mount a generated CA.
  // Public clients therefore need the host's system trust store, read-only.
  "/etc/ssl",
] as const;

const hostExecutableRoots = ["/usr/bin", "/bin", "/usr/local/bin"] as const;

const resolveHostExecutable = (executable: string): string | undefined => {
  // Shell executors submit a bare name (for example "bash"). Resolve it only
  // against the fixed toolchain mounts, never the inherited PATH or cwd.
  const candidates = isAbsolute(executable)
    ? [executable]
    : /^[A-Za-z0-9][A-Za-z0-9._+-]*$/u.test(executable)
      ? hostExecutableRoots.map((root) => resolve(root, executable))
      : [];
  for (const candidate of candidates) {
    try {
      const canonical = realpathSync.native(candidate);
      if (hostExecutableRoots.some((root) => within(root, canonical)))
        return canonical;
    } catch {
      // A missing fixed toolchain root/name does not enable a PATH fallback.
    }
  }
  return undefined;
};

const within = (root: string, candidate: string): boolean => {
  const path = relative(root, candidate);
  return (
    path === "" ||
    (!path.startsWith(`..${sep}`) && path !== ".." && !isAbsolute(path))
  );
};

const canonicalRoots = (
  policy: OsEnforcedSandboxProcessPolicyAny,
  handle: SandboxHandle,
):
  | ReadonlyArray<{
      readonly ref: string;
      readonly root: string;
      readonly access: "ReadOnly" | "ReadWrite";
    }>
  | undefined => {
  const boundMounts = handle.mounts;
  if (
    boundMounts === undefined ||
    boundMounts.length === 0 ||
    policy.admittedMounts.length !== boundMounts.length
  )
    return undefined;
  const roots: Array<{
    ref: string;
    root: string;
    access: "ReadOnly" | "ReadWrite";
  }> = [];
  for (const mount of policy.admittedMounts) {
    if (!safeRef.test(mount.ref) || !isAbsolute(mount.rootPath))
      return undefined;
    const bound = boundMounts.find((candidate) => candidate.ref === mount.ref);
    if (bound === undefined || bound.access !== mount.access) return undefined;
    let root: string;
    let boundRoot: string;
    try {
      root = realpathSync.native(mount.rootPath);
      boundRoot = realpathSync.native(bound.rootPath);
    } catch {
      return undefined;
    }
    if (root !== mount.rootPath || boundRoot !== root) return undefined;
    if (policy.profile === "ReadOnly" && mount.access !== "ReadOnly")
      return undefined;
    roots.push({ ref: mount.ref, root, access: mount.access });
  }
  if (new Set(roots.map((mount) => mount.ref)).size !== roots.length)
    return undefined;
  return roots;
};

const resolveInMount = (
  root: string,
  relativePath: string,
): string | undefined => {
  if (
    relativePath.length === 0 ||
    relativePath.includes("\0") ||
    isAbsolute(relativePath)
  )
    return undefined;
  const segments = relativePath.split(/[\\/]/u);
  if (segments.some((segment) => segment === "..")) return undefined;
  const candidate = resolve(root, relativePath);
  try {
    const canonical = realpathSync.native(candidate);
    return within(root, canonical) ? canonical : undefined;
  } catch {
    return undefined;
  }
};

const mappedPath = (
  roots: ReadonlyArray<{ readonly ref: string; readonly root: string }>,
  hostPath: string,
): string | undefined => {
  if (!isAbsolute(hostPath)) return undefined;
  let canonical: string;
  try {
    canonical = realpathSync.native(hostPath);
  } catch {
    return undefined;
  }
  const root = roots.find((candidate) => within(candidate.root, canonical));
  if (root === undefined) return undefined;
  const subpath = relative(root.root, canonical).split(sep).join("/");
  return subpath.length === 0
    ? `/arbor/mounts/${root.ref}`
    : `/arbor/mounts/${root.ref}/${subpath}`;
};

const validatePlanInput = (input: PlanInput) => {
  if (input.policy.providerId !== LINUX_BWRAP_PROVIDER_ID)
    return {
      _tag: "Unavailable" as const,
      failureCode: "ProviderBindingMismatch",
    };
  if (input.policy.sandboxHandleId !== input.handle.handleId)
    return {
      _tag: "Unavailable" as const,
      failureCode: "HandleBindingMismatch",
    };
  if (
    !Object.values(input.policy.limits).every(
      (value) => Number.isSafeInteger(value) && value > 0,
    )
  )
    return { _tag: "Unavailable" as const, failureCode: "InvalidLimits" };
  const roots = canonicalRoots(input.policy, input.handle);
  if (roots === undefined)
    return { _tag: "Unavailable" as const, failureCode: "MountBindingInvalid" };
  if (decodeNetworkPolicyV1(input.policy.networkPolicy) === undefined)
    return {
      _tag: "Unavailable" as const,
      failureCode: "InvalidNetworkPolicy",
    };
  if (
    input.policy.networkPolicy.mode !== "Disabled" &&
    input.networkBroker === undefined
  )
    return {
      _tag: "Unavailable" as const,
      failureCode: "NetworkBrokerUnavailable",
    };
  if (
    input.policy.networkPolicy.mode === "Disabled" &&
    input.networkBroker !== undefined
  )
    return {
      _tag: "Unavailable" as const,
      failureCode: "InvalidNetworkPolicy",
    };
  if (
    input.policy.kind === "OsEnforcedProcessPolicyV2" ||
    input.policy.kind === "IndependentVerificationProcessPolicyV1"
  ) {
    if (
      decodeNetworkBrokerControlsV2(input.policy.networkBrokerControls) ===
        undefined ||
      input.policy.networkBrokerControls.mode !==
        input.policy.networkPolicy.mode
    )
      return {
        _tag: "Unavailable" as const,
        failureCode: "InvalidNetworkBrokerControls",
      };
    const brokerProtocol =
      input.networkBroker === undefined
        ? undefined
        : (input.networkBroker.protocol ??
          (input.networkBroker.certificatePath === undefined ? "V2" : "V1"));
    if (
      input.policy.providerId !== LINUX_BWRAP_PROVIDER_ID ||
      (input.policy.networkBrokerControls.mode !== "Disabled" &&
        brokerProtocol !== "V2")
    )
      return {
        _tag: "Unavailable" as const,
        failureCode: "NetworkBrokerProtocolMismatch",
      };
  } else if (
    input.networkBroker !== undefined &&
    (input.networkBroker.protocol ??
      (input.networkBroker.certificatePath === undefined ? "V2" : "V1")) !==
      "V1"
  ) {
    return {
      _tag: "Unavailable" as const,
      failureCode: "NetworkBrokerProtocolMismatch",
    };
  }
  if (input.networkBroker !== undefined) {
    const binding = input.networkBroker;
    const protocol =
      binding.protocol ?? (binding.certificatePath === undefined ? "V2" : "V1");
    try {
      const paths = [
        binding.socketDirectory,
        binding.socketPath,
        binding.helperPath,
        ...(protocol === "V1" && binding.certificatePath !== undefined
          ? [binding.certificatePath]
          : []),
      ];
      if (
        !paths.every(
          (path) => isAbsolute(path) && realpathSync.native(path) === path,
        ) ||
        binding.socketPath !==
          resolve(binding.socketDirectory, "egress.sock") ||
        !Number.isSafeInteger(binding.proxyPort) ||
        binding.proxyPort < 1024 ||
        binding.proxyPort > 65535 ||
        !lstatSync(binding.socketDirectory).isDirectory() ||
        !lstatSync(binding.socketPath).isSocket() ||
        (protocol === "V1" &&
          (binding.certificatePath === undefined ||
            !lstatSync(binding.certificatePath).isFile())) ||
        !lstatSync(binding.helperPath).isFile() ||
        readdirSync(binding.socketDirectory).some(
          (name) => name !== "egress.sock",
        )
      )
        throw new Error("invalid broker binding");
    } catch {
      return {
        _tag: "Unavailable" as const,
        failureCode: "NetworkBrokerBindingInvalid",
      };
    }
  }
  if (input.args.some((arg) => arg.includes("\0")))
    return { _tag: "Unavailable" as const, failureCode: "InvalidArgument" };
  const cwdMount = roots.find((mount) => mount.ref === input.cwd.mount);
  if (cwdMount === undefined)
    return { _tag: "Unavailable" as const, failureCode: "CwdMountNotAdmitted" };
  const cwd = resolveInMount(cwdMount.root, input.cwd.path);
  if (cwd === undefined)
    return {
      _tag: "Unavailable" as const,
      failureCode: "PathOutsideAdmittedMount",
    };
  const mappedCwd = mappedPath(roots, cwd);
  const mappedExecutable = mappedPath(roots, input.executable);
  const hostExecutable = resolveHostExecutable(input.executable);
  if (
    mappedCwd === undefined ||
    (mappedExecutable === undefined && hostExecutable === undefined)
  )
    return {
      _tag: "Unavailable" as const,
      failureCode: "ExecutableOutsideAdmittedMount",
    };
  const env = projectSandboxEnvironment(
    sandboxEnvironment(input.ambientEnvironment),
    input.policy.environmentAllowlist.filter((name) =>
      SANDBOX_ENV_ALLOWLIST.includes(name),
    ),
  );
  if (Object.values(env).some((value) => value?.includes("\0")))
    return {
      _tag: "Unavailable" as const,
      failureCode: "InvalidEnvironmentValue",
    };
  if (input.policy.environmentAllowlist.some((name) => !safeEnvName.test(name)))
    return {
      _tag: "Unavailable" as const,
      failureCode: "InvalidEnvironmentAllowlist",
    };
  return {
    _tag: "Ready" as const,
    roots,
    cwd: mappedCwd,
    executable: mappedExecutable ?? (hostExecutable as string),
    env,
  };
};

/** Build the closed bubblewrap argv. It never spawns. */
export const buildBwrapPlan = (input: PlanInput): PolicyPlan => {
  // A normal WorkspaceWrite tuple is not proof for this new binding/mount
  // combination. Keep it unavailable until the actual qualification reader
  // and production environment lifecycle are connected.
  const validated = validatePlanInput(input);
  if (validated._tag !== "Ready") return validated;
  const commandFilter = linuxCommandFilter(process.arch);
  if (commandFilter === undefined)
    return { _tag: "Unavailable", failureCode: "CommandFilterUnavailable" };
  const filterOctal = Array.from(
    Buffer.from(commandFilter, "base64"),
    (byte) => `\\0${byte.toString(8).padStart(3, "0")}`,
  ).join("");
  const argv = [
    "--die-with-parent",
    "--new-session",
    "--unshare-user",
    "--unshare-pid",
    "--unshare-ipc",
    "--unshare-uts",
    "--unshare-net",
    "--disable-userns",
    "--assert-userns-disabled",
    "--cap-drop",
    "ALL",
    "--clearenv",
    "--tmpfs",
    "/",
    "--dir",
    "/arbor",
    "--dir",
    "/arbor/runtime",
    "--dir",
    "/arbor/mounts",
    "--proc",
    "/proc",
    // The trusted relay shares this PID namespace. Denying ptrace alone does
    // not prevent writes through /proc/<relay>/mem by a same-user command.
    "--remount-ro",
    "/proc",
    "--dev",
    "/dev",
    "--tmpfs",
    "/tmp",
  ];
  for (const mount of validated.roots) {
    argv.push(
      mount.access === "ReadWrite" ? "--bind" : "--ro-bind",
      mount.root,
      `/arbor/mounts/${mount.ref}`,
    );
  }
  // The project mounts are the only writable user resources. A process still
  // needs the host's read-only ELF loader and ordinary developer tools such as
  // bash, git and the system compiler. These fixed roots are never derived
  // from a request and are mounted read-only inside the private root.
  for (const root of hostToolchainRoots) {
    if (existsSync(root)) argv.push("--ro-bind", root, root);
  }
  let networkNodeHost: string | undefined;
  const networkNodeInSandbox = "/arbor/runtime/node";
  const protocol =
    input.networkBroker === undefined
      ? undefined
      : (input.networkBroker.protocol ??
        (input.networkBroker.certificatePath === undefined ? "V2" : "V1"));
  if (input.networkBroker !== undefined) {
    try {
      networkNodeHost = realpathSync.native(process.execPath);
    } catch {
      networkNodeHost = undefined;
    }
    if (networkNodeHost === undefined) {
      return {
        _tag: "Unavailable",
        failureCode: "NetworkRuntimeUnavailable",
      };
    }
    argv.push(
      "--ro-bind",
      input.networkBroker.socketDirectory,
      "/arbor/network",
      "--ro-bind",
      networkNodeHost,
      networkNodeInSandbox,
      "--ro-bind",
      input.networkBroker.helperPath,
      "/arbor/runtime/network-proxy-helper.mjs",
    );
    if (
      protocol === "V1" &&
      input.networkBroker.certificatePath !== undefined
    ) {
      argv.push(
        "--ro-bind",
        input.networkBroker.certificatePath,
        "/arbor/runtime/network-authority.pem",
      );
    }
  }
  const safePath = "/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin";
  const env: NodeJS.ProcessEnv = {
    ...validated.env,
    PATH: safePath,
    HOME: "/tmp",
    TMPDIR: "/tmp",
    ...(input.networkBroker === undefined
      ? {}
      : protocol === "V1"
        ? {
            HTTP_PROXY: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            HTTPS_PROXY: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            ALL_PROXY: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            http_proxy: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            https_proxy: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            all_proxy: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            NO_PROXY: "",
            no_proxy: "",
            CURL_CA_BUNDLE: "/arbor/runtime/network-authority.pem",
            SSL_CERT_FILE: "/arbor/runtime/network-authority.pem",
            NODE_EXTRA_CA_CERTS: "/arbor/runtime/network-authority.pem",
            GIT_SSL_CAINFO: "/arbor/runtime/network-authority.pem",
            REQUESTS_CA_BUNDLE: "/arbor/runtime/network-authority.pem",
          }
        : {
            HTTP_PROXY: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            HTTPS_PROXY: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            ALL_PROXY: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            http_proxy: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            https_proxy: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            all_proxy: `http://127.0.0.1:${input.networkBroker.proxyPort}`,
            NO_PROXY: "",
            no_proxy: "",
          }),
  };
  for (const [key, value] of Object.entries(env)) {
    if (value !== undefined) argv.push("--setenv", key, value);
  }
  const launch = [
    "set -euo pipefail",
    "umask 077",
    "set -C",
    // The private /tmp is initially empty. No project process runs before
    // setpriv loads this filter, and descendants cannot remove an inherited
    // seccomp filter by replacing the file or executing setpriv again.
    `printf '%b' '${filterOctal}' > /tmp/arbor-command-filter.bpf`,
  ];
  if (input.networkBroker !== undefined && networkNodeHost !== undefined) {
    launch.push(
      // A command must not be able to signal the unfiltered relay into
      // opening Node's inspector and executing arbitrary relay-side code.
      '"/arbor/runtime/node" --disable-sigusr1 /arbor/runtime/network-proxy-helper.mjs /arbor/network/egress.sock "$1" /tmp/arbor-network-ready &',
      "proxy_pid=$!",
      'trap \'kill "$proxy_pid" 2>/dev/null || true; wait "$proxy_pid" 2>/dev/null || true\' EXIT',
      "shift",
      "for attempt in {1..250}; do",
      "  test -f /tmp/arbor-network-ready && break",
      '  kill -0 "$proxy_pid" 2>/dev/null || exit 127',
      "  sleep 0.02",
      "done",
      "test -f /tmp/arbor-network-ready || exit 127",
    );
  }
  launch.push(input.networkBroker === undefined ? 'exec "$@"' : '"$@"');
  argv.push(
    "--chdir",
    validated.cwd,
    "--",
    "/bin/bash",
    "--noprofile",
    "--norc",
    "-c",
    launch.join("\n"),
    "arbor-command-launch",
    ...(input.networkBroker === undefined
      ? []
      : [String(input.networkBroker.proxyPort)]),
    LINUX_SANDBOX_EXECUTABLES.setpriv,
    "--no-new-privs",
    "--seccomp-filter",
    "/tmp/arbor-command-filter.bpf",
    validated.executable,
    ...input.args,
  );
  return {
    _tag: "Ready",
    argv,
    cwd: "/",
    env,
    requestedLimits: input.policy.limits,
  };
};

const seatbeltQuote = (value: string): string | undefined => {
  if (!isAbsolute(value) || value.includes("\0") || /[\r\n]/u.test(value))
    return undefined;
  return JSON.stringify(value);
};

/** Generate a deny-default macOS Seatbelt profile for the exact admitted roots. */
export const buildSeatbeltProfile = (input: {
  readonly policy: OsEnforcedSandboxProcessPolicy;
  readonly handle: SandboxHandle;
  readonly executable: string;
}): SeatbeltProfile => {
  const policy = input.policy;
  if (policy.providerId !== MACOS_SEATBELT_PROVIDER_ID)
    return { _tag: "Unavailable", failureCode: "ProviderBindingMismatch" };
  if (policy.sandboxHandleId !== input.handle.handleId)
    return { _tag: "Unavailable", failureCode: "HandleBindingMismatch" };
  if (
    !Object.values(policy.limits).every(
      (value) => Number.isSafeInteger(value) && value > 0,
    )
  )
    return { _tag: "Unavailable", failureCode: "InvalidLimits" };
  if (policy.networkPolicy.mode !== "Disabled")
    return { _tag: "Unavailable", failureCode: "NetworkBrokerUnavailable" };
  if (policy.networkPolicy.destinations.length !== 0)
    return { _tag: "Unavailable", failureCode: "InvalidNetworkPolicy" };
  const roots = canonicalRoots(policy, input.handle);
  if (roots === undefined)
    return { _tag: "Unavailable", failureCode: "MountBindingInvalid" };
  const executable = mappedPath(roots, input.executable);
  if (executable === undefined)
    return {
      _tag: "Unavailable",
      failureCode: "ExecutableOutsideAdmittedMount",
    };
  const quotedExecutable = seatbeltQuote(realpathSync.native(input.executable));
  if (quotedExecutable === undefined)
    return { _tag: "Unavailable", failureCode: "InvalidExecutablePath" };
  const lines = [
    "(version 1)",
    "(deny default)",
    "(allow process-fork)",
    `(allow process-exec (literal ${quotedExecutable}))`,
  ];
  for (const mount of roots) {
    const quoted = seatbeltQuote(mount.root);
    if (quoted === undefined)
      return { _tag: "Unavailable", failureCode: "InvalidMountPath" };
    lines.push(`(allow file-read* (subpath ${quoted}))`);
    if (mount.access === "ReadWrite")
      lines.push(`(allow file-write* (subpath ${quoted}))`);
  }
  lines.push("(deny network*)");
  return {
    _tag: "Ready",
    source: `${lines.join("\n")}\n`,
    requestedLimits: policy.limits,
  };
};

