/** Actual supervisor used by runtime and the independent installer controls.
 * This is a plan executor, not a Supported capability or an authority issuer.
 * The daemon reaches it only after the SandboxProcessPort admission checks. */
export const runSystemdBwrap = (
  plan: Extract<PolicyPlan, { readonly _tag: "Ready" }>,
  requestedTimeoutMs: number,
  signal: AbortSignal,
): Promise<Extract<SandboxProcessOutcome, { readonly _tag: "Completed" }>> => {
  signal.throwIfAborted();
  const unit = `arbor-sandbox-${process.pid}-${Date.now()}-${Math.random()
    .toString(16)
    .slice(2)}`;
  const cpuSeconds = Math.max(
    1,
    Math.ceil(plan.requestedLimits.cpuTimeMs / 1000),
  );
  const wallTimeout = Math.max(
    1,
    Math.min(plan.requestedLimits.wallTimeMs, requestedTimeoutMs),
  );
  // These variables are needed by the host-side systemd client to address the
  // user's manager. They are never passed through to the child: bubblewrap
  // starts with --clearenv and receives only the closed plan.env below.
  const supervisorEnvironment: NodeJS.ProcessEnv = {
    PATH: process.env.PATH ?? "/usr/bin:/bin",
    ...(process.env.XDG_RUNTIME_DIR === undefined
      ? {}
      : { XDG_RUNTIME_DIR: process.env.XDG_RUNTIME_DIR }),
    ...(process.env.DBUS_SESSION_BUS_ADDRESS === undefined
      ? {}
      : { DBUS_SESSION_BUS_ADDRESS: process.env.DBUS_SESSION_BUS_ADDRESS }),
  };
  const args = [
    "--user",
    "--wait",
    "--collect",
    "--pipe",
    `--unit=${unit}`,
    `--property=MemoryMax=${plan.requestedLimits.memoryBytes}`,
    "--property=MemorySwapMax=0",
    "--property=OOMPolicy=kill",
    `--property=TasksMax=${plan.requestedLimits.processCount}`,
    "--property=CPUQuota=100%",
    `--property=LimitCPU=${cpuSeconds}s`,
    `--property=RuntimeMaxSec=${wallTimeout}ms`,
    "--property=KillMode=control-group",
    "--property=TimeoutStopSec=1s",
    "--",
    LINUX_SANDBOX_EXECUTABLES.bwrap,
    ...plan.argv,
  ];
  const controlUnit = (operation: "stop" | "show") =>
    new Promise<{ readonly ok: boolean; readonly stdout: string }>((done) => {
      execFile(
        LINUX_SANDBOX_EXECUTABLES.systemctl,
        [
          "--user",
          operation,
          ...(operation === "show"
            ? ["--property=LoadState", "--property=ActiveState"]
            : []),
          unit,
        ],
        {
          env: supervisorEnvironment,
          timeout: 5000,
          encoding: "utf8",
          windowsHide: true,
        },
        (error, stdout) => done({ ok: error === null, stdout }),
      );
    });
  let clientFinished = false;
  let stopPromise: Promise<void> | undefined;
  const stopUnit = (): Promise<void> => {
    stopPromise ??= (async () => {
      // A cancellation can arrive before systemd-run has submitted its unit.
      // Do not accept "not-found" while the client can still create it. Keep
      // the client alive, stop the exact unit once it exists, and await both.
      for (;;) {
        if ((await controlUnit("stop")).ok) return;
        const state = await controlUnit("show");
        const fields = state.stdout.trim().split(/\r?\n/u);
        if (
          fields.includes("LoadState=not-found") &&
          fields.includes("ActiveState=inactive")
        ) {
          if (clientFinished) return;
          await new Promise<void>((resolveWait) => setTimeout(resolveWait, 20));
          continue;
        }
        throw new NativeProcessCleanupFailure(
          "sandbox process group cleanup could not be confirmed",
        );
      }
    })();
    return stopPromise;
  };
  return new Promise((resolveResult, rejectResult) => {
    let timedOut = false;
    const cancel = () => {
      void stopUnit().catch(() => {});
    };
    signal.addEventListener("abort", cancel, { once: true });
    const timer = setTimeout(() => {
      timedOut = true;
      void stopUnit().catch(() => {});
    }, wallTimeout + 250);
    execFile(
      LINUX_SANDBOX_EXECUTABLES.systemdRun,
      args,
      {
        cwd: "/",
        env: supervisorEnvironment,
        timeout: wallTimeout + 5000,
        maxBuffer:
          plan.requestedLimits.stdoutBytes + plan.requestedLimits.stderrBytes,
        encoding: "buffer",
        windowsHide: true,
      },
      (error, stdout, stderr) => {
        clientFinished = true;
        clearTimeout(timer);
        signal.removeEventListener("abort", cancel);
        const out = Buffer.isBuffer(stdout)
          ? stdout
          : Buffer.from(stdout ?? "");
        const err = Buffer.isBuffer(stderr)
          ? stderr
          : Buffer.from(stderr ?? "");
        // systemd-run normally returns before the host-side safety timer when
        // RuntimeMaxSec terminates the unit. Its structured stderr is the
        // authoritative signal for that boundary; relying only on the local
        // timer would misclassify a supervised timeout as an ordinary exit.
        const supervisorTimedOut = /Finished with result: timeout\b/u.test(
          err.toString("utf8"),
        );
        const effectiveTimedOut = timedOut || supervisorTimedOut;
        const truncated =
          typeof error === "object" &&
          error !== null &&
          "code" in error &&
          error.code === "ERR_CHILD_PROCESS_STDIO_MAXBUFFER";
        const launchError =
          error !== null &&
          !timedOut &&
          !truncated &&
          !(
            typeof error === "object" &&
            "code" in error &&
            typeof error.code === "number"
          );
        const exitCode =
          error !== null &&
          typeof error === "object" &&
          "code" in error &&
          typeof error.code === "number"
            ? error.code
            : error === null
              ? 0
              : 1;
        const outcome = {
          _tag: "Completed" as const,
          exitCode,
          stdout: out
            .subarray(0, plan.requestedLimits.stdoutBytes)
            .toString("utf8"),
          stderr: err
            .subarray(0, plan.requestedLimits.stderrBytes)
            .toString("utf8"),
          timedOut: effectiveTimedOut,
          truncated:
            truncated ||
            out.byteLength > plan.requestedLimits.stdoutBytes ||
            err.byteLength > plan.requestedLimits.stderrBytes,
        };
        const finish = async () => {
          // maxBuffer/execFile timeout can kill only the supervisor client.
          // Cancellation also owns the service's entire descendant group.
          if (truncated || timedOut || signal.aborted || launchError)
            await stopUnit();
          if (launchError) throw error;
          return outcome;
        };
        void finish().then(resolveResult, rejectResult);
      },
    );
  });
};

export const makeNativePosixSandboxProcessPort = (
  options: NativePosixSandboxOptions = {},
): SandboxProcessPortService => {
  const platform = options.platform ?? process.platform;
  const linuxProbe =
    options.linuxProbe ?? (() => probeLinuxBwrap({ platform }));
  const seatbeltProbe =
    options.seatbeltProbe ?? (() => probeMacOSSeatbelt({ platform }));
  const probes: Readonly<Record<string, () => Promise<NativePosixCapability>>> =
    {
      [LINUX_BWRAP_PROVIDER_ID]: linuxProbe,
      [MACOS_SEATBELT_PROVIDER_ID]: seatbeltProbe,
    };
  const service: SandboxProcessPortService = {
    capabilities: () =>
      Effect.promise(() =>
        Promise.all(
          Object.entries(probes).map(async ([providerId, probe]) => {
            try {
              return await probe();
            } catch {
              return unavailableCapability(providerId, "CapabilityProbeFailed");
            }
          }),
        ),
      ),
    run: (
      request: SandboxProcessRequest,
    ): Effect.Effect<SandboxProcessProviderOutcome> =>
      Effect.callback<SandboxProcessProviderOutcome>((resume, signal) => {
        const operation = (async (): Promise<SandboxProcessProviderOutcome> => {
          signal.throwIfAborted();
          const probe = probes[request.policy.providerId];
          if (probe === undefined)
            return unavailable(request.policy, "ProviderNotFound", null);
          const capability = await probe();
          signal.throwIfAborted();
          if (capability.failureCode !== null)
            return unavailable(
              request.policy,
              capability.failureCode,
              capability.probeEvidenceRef,
              capability.capabilityRevision,
            );
          if (
            capability.status !== "Supported" ||
            capability.profiles.length === 0 ||
            !capability.profiles.includes(request.policy.profile) ||
            capability.networkModes.length === 0 ||
            !capability.networkModes.includes(request.policy.networkPolicy.mode)
          )
            return unavailable(
              request.policy,
              "ExperimentalProviderExecutionDisabled",
              capability.probeEvidenceRef,
              capability.capabilityRevision,
            );
          if (
            capability.providerId !== request.policy.providerId ||
            capability.providerVersion !== request.policy.providerVersion ||
            capability.capabilityRevision !==
              request.policy.capabilityRevision ||
            capability.boundary !== request.policy.boundary ||
            capability.enforcementRuleSetDigest === null ||
            capability.enforcementRuleSetDigest !==
              request.policy.enforcementRuleSetDigest ||
            capability.qualificationEvidenceRef === null ||
            !(
              capability.qualificationEvidenceRefs?.includes(
                request.policy.qualificationEvidenceRef,
              ) ??
              capability.qualificationEvidenceRef ===
                request.policy.qualificationEvidenceRef
            )
          )
            return unavailable(
              request.policy,
              "ProviderBindingMismatch",
              capability.probeEvidenceRef,
              capability.capabilityRevision,
            );
          if (
            request.policy.kind === "OsEnforcedProcessPolicyV2" ||
            request.policy.kind === "IndependentVerificationProcessPolicyV1"
          ) {
            const proof = capability.qualificationTuples?.find(
              (tuple) =>
                tuple.profile === request.policy.profile &&
                tuple.networkMode === request.policy.networkPolicy.mode &&
                tuple.qualificationEvidenceRef ===
                  request.policy.qualificationEvidenceRef,
            );
            if (proof === undefined)
              return unavailable(
                request.policy,
                "QualificationTupleMismatch",
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
            if (
              Object.entries(request.policy.limits).some(
                ([key, value]) =>
                  !Number.isSafeInteger(value) ||
                  value <= 0 ||
                  !Number.isSafeInteger(
                    proof.validatedLimits[
                      key as keyof typeof proof.validatedLimits
                    ],
                  ) ||
                  value >
                    proof.validatedLimits[
                      key as keyof typeof proof.validatedLimits
                    ],
              )
            )
              return unavailable(
                request.policy,
                "QualificationLimitsExceeded",
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
          }
          if (
            request.policy.kind === "IndependentVerificationProcessPolicyV1"
          ) {
            const ref =
              request.policy.verificationMountQualificationEvidenceRef;
            if (!/^blob:sha256:[0-9a-f]{64}$/u.test(ref))
              return unavailable(
                request.policy,
                "VerificationQualificationEvidenceInvalid",
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
            if (options.readVerificationQualificationEvidence === undefined)
              return unavailable(
                request.policy,
                "VerificationQualificationEvidenceUnavailable",
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
            const evidence =
              await options.readVerificationQualificationEvidence(
                ref as `blob:sha256:${string}`,
              );
            if (evidence === undefined) {
              return unavailable(
                request.policy,
                "VerificationQualificationEvidenceUnavailable",
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
            }
            if (
              !matchesIndependentVerificationQualification({
                request,
                evidence,
                reference: ref as `blob:sha256:${string}`,
              })
            ) {
              return unavailable(
                request.policy,
                "VerificationQualificationEvidenceInvalid",
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
            }
          }
          let networkBroker: SandboxNetworkBrokerBindingAny | undefined;
          try {
            if (request.policy.networkPolicy.mode !== "Disabled") {
              if (options.networkBrokerFactory === undefined)
                return unavailable(
                  request.policy,
                  "NetworkBrokerUnavailable",
                  capability.probeEvidenceRef,
                  capability.capabilityRevision,
                );
              networkBroker = await options.networkBrokerFactory(
                request.policy.networkPolicy,
                request.policy.kind === "OsEnforcedProcessPolicyV2" ||
                  request.policy.kind ===
                    "IndependentVerificationProcessPolicyV1"
                  ? "V2"
                  : "V1",
              );
            }
          } catch {
            return unavailable(
              request.policy,
              "NetworkBrokerUnavailable",
              capability.probeEvidenceRef,
              capability.capabilityRevision,
            );
          }
          try {
            signal.throwIfAborted();
            const plan = buildBwrapPlan({ ...request, networkBroker });
            if (plan._tag !== "Ready") {
              return unavailable(
                request.policy,
                plan.failureCode,
                capability.probeEvidenceRef,
                capability.capabilityRevision,
              );
            }
            const execute =
              options.execute ??
              ((value, currentRequest, currentSignal) =>
                runSystemdBwrap(
                  value,
                  currentRequest.timeoutMs,
                  currentSignal,
                ));
            return await execute(plan, request, signal);
          } catch (error) {
            if (error instanceof NativeProcessCleanupFailure) throw error;
            return unavailable(
              request.policy,
              "ProcessLaunchFailed",
              capability.probeEvidenceRef,
              capability.capabilityRevision,
            );
          } finally {
            await closeNetworkBroker(networkBroker);
          }
        })().catch((error) => {
          if (error instanceof NativeProcessCleanupFailure) throw error;
          return unavailable(request.policy, "CapabilityProbeFailed", null);
        });
        void operation.then(
          (outcome) => resume(Effect.succeed(outcome)),
          (error) => resume(Effect.die(error)),
        );
        // Effect aborts the signal before this finalizer. Interruption waits
        // for both the supervised service and its broker; an unconfirmed
        // cleanup is a defect, never an ordinary no-effect Unavailable result.
        return Effect.promise(async () => {
          await operation;
        });
      }),
  };
  return service;
};

export const NativePosixSandboxProcessPortLive = (
  options: NativePosixSandboxOptions = {},
): Layer.Layer<SandboxProcessPort> =>
  Layer.succeed(SandboxProcessPort, makeNativePosixSandboxProcessPort(options));

const unavailableCapability = (
  providerId: string,
  failureCode: string,
): NativePosixCapability => ({
  providerId,
  providerVersion: EXPERIMENTAL_VERSION,
  capabilityRevision: "probe-failed-v1",
  probeEvidenceRef: null,
  enforcementRuleSetDigest: null,
  qualificationEvidenceRef: null,
  status: "Experimental",
  boundary: "OsEnforced",
  profiles: [],
  networkModes: [],
  failureCode,
  prerequisites: { capabilityProbe: "Unavailable" },
});

const unavailable = (
  policy: OsEnforcedSandboxProcessPolicyAny,
  failureCode: string,
  probeEvidenceRef: string | null,
  capabilityRevision: string = policy.capabilityRevision,
): SandboxProcessProviderOutcome => {
  if (process.env.ARBOR_DEBUG_SANDBOX_FAILURES === "1") {
    console.error("sandbox unavailable", {
      kind: policy.kind,
      profile: policy.profile,
      networkMode: policy.networkPolicy.mode,
      failureCode,
    });
  }
  return {
    _tag: "Unavailable",
    providerId: policy.providerId as SandboxProviderId,
    providerVersion: policy.providerVersion,
    capabilityRevision,
    probeEvidenceRef,
    failureCode,
  };
};

const hasExactKeys = (
  value: Record<string, unknown>,
  keys: ReadonlyArray<string>,
): boolean =>
  Object.keys(value).length === keys.length &&
  keys.every((key) => Object.hasOwn(value, key));

/**
 * A verification qualification record is only useful when it describes the
 * exact process request that is about to run.  The record is not an authority
 * row and this check does not turn it into one; it prevents a stale or
 * upper-layer-forged record from being accepted for a different binding or
 * mount set.  The actual provider Supported tuple is checked separately above.
 */
const matchesIndependentVerificationQualification = (input: {
  readonly request: SandboxProcessRequest;
  readonly evidence: string;
  readonly reference: `blob:sha256:${string}`;
}): boolean => {
  const policy = input.request.policy;
  if (policy.kind !== "IndependentVerificationProcessPolicyV1") return false;
  const handleMounts = input.request.handle.mounts;
  if (handleMounts === undefined) return false;
  try {
    const digest = createHash("sha256")
      .update(input.evidence, "utf8")
      .digest("hex");
    if (`blob:sha256:${digest}` !== input.reference) return false;
    const parsed = JSON.parse(input.evidence) as Record<string, unknown>;
    if (
      !hasExactKeys(parsed, [
        "version",
        "kind",
        "binding",
        "provider",
        "mounts",
      ]) ||
      parsed.version !== 1 ||
      parsed.kind !== "IndependentVerificationMountQualification" ||
      typeof parsed.binding !== "object" ||
      parsed.binding === null ||
      Array.isArray(parsed.binding) ||
      typeof parsed.provider !== "object" ||
      parsed.provider === null ||
      Array.isArray(parsed.provider) ||
      !Array.isArray(parsed.mounts)
    )
      return false;

    const bindingJson = JSON.stringify(parsed.binding);
    const binding = decodeCanonicalVerificationSandboxBindingV1(bindingJson);
    if (
      binding === undefined ||
      encodeVerificationSandboxBindingV1(binding) !== bindingJson ||
      encodeVerificationSandboxBindingV1(binding) !==
        encodeVerificationSandboxBindingV1(policy.verificationBinding)
    )
      return false;

    const provider = parsed.provider as Record<string, unknown>;
    if (
      !hasExactKeys(provider, [
        "providerId",
        "providerVersion",
        "capabilityRevision",
        "osBuild",
        "profile",
        "networkMode",
        "qualificationEvidenceRef",
      ]) ||
      provider.providerId !== policy.providerId ||
      provider.providerVersion !== policy.providerVersion ||
      String(provider.capabilityRevision) !== policy.capabilityRevision ||
      provider.osBuild !== release() ||
      provider.profile !== policy.profile ||
      provider.networkMode !== policy.networkPolicy.mode ||
      provider.qualificationEvidenceRef !== policy.qualificationEvidenceRef
    )
      return false;

    if (parsed.mounts.length !== handleMounts.length) return false;
    return parsed.mounts.every((candidate, index) => {
      if (
        typeof candidate !== "object" ||
        candidate === null ||
        Array.isArray(candidate)
      )
        return false;
      const mount = candidate as Record<string, unknown>;
      const handleMount = handleMounts[index];
      const policyMount = policy.admittedMounts[index];
      return (
        handleMount !== undefined &&
        policyMount !== undefined &&
        hasExactKeys(mount, ["ref", "access"]) &&
        mount.ref === handleMount.ref &&
        mount.ref === policyMount.ref &&
        mount.access === handleMount.access &&
        mount.access === policyMount.access
      );
    });
  } catch {
    return false;
  }
};

